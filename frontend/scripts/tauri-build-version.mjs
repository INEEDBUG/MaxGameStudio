import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, statSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { delimiter, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveCargoReleaseRoot } from "./cargo-release-root.mjs";
import { prepareWindowsResourceBundle } from "./windows-resource-bundle.mjs";
import {
  assertPeX64,
  isGnuBuild,
  resolveLibunwindSource,
  stageLibunwind,
} from "./tauri-native-runtime.mjs";

const version = process.argv.slice(2).find((arg) => arg !== "--")?.trim();
if (!version || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error("Usage: pnpm run desktop:build:ver -- <x.y.z>");
  process.exit(1);
}

const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const tauriRoot = join(frontendRoot, "src-tauri");
const nativeRuntime = process.env.MGS_MAIN_NATIVE_PACKAGE === "1";
const pathKey = Object.keys(process.env).find((key) => key.toLowerCase() === "path") || "PATH";
const buildEnv = {
  ...process.env,
  CS2_INSIGHT_APP_VERSION: version,
  [pathKey]: [dirname(process.execPath), process.env[pathKey] || ""]
    .filter(Boolean)
    .join(delimiter),
};
const releaseRoot = resolveCargoReleaseRoot({
  frontendRoot,
  cargoTargetDir: buildEnv.CARGO_TARGET_DIR,
  cargoBuildTarget: buildEnv.CARGO_BUILD_TARGET,
});
const gnullvmBuild = /gnullvm/i.test(
  [buildEnv.RUSTUP_TOOLCHAIN, buildEnv.CARGO_BUILD_TARGET, buildEnv.HOST]
    .filter(Boolean)
    .join(" "),
);
if (gnullvmBuild) {
  const configuredRuntime = buildEnv.CS2_LIBUNWIND_DLL || buildEnv.CS2_INSIGHT_LIBUNWIND_DLL;
  const runtime = configuredRuntime
    ? resolveLibunwindSource({ ...buildEnv, CS2_INSIGHT_LIBUNWIND_DLL: configuredRuntime })
    : resolveLibunwindSource(buildEnv);
  // build.rs uses this name for LLVM-MinGW, while the wrapper's runtime
  // helper uses the project-scoped name below.
  buildEnv.CS2_LIBUNWIND_DLL = runtime;
  buildEnv.CS2_INSIGHT_LIBUNWIND_DLL = runtime;
}

// Updater (.sig) signing: fall back to the maintainer keypair generated by
// `tauri signer generate`. The default key uses an empty password, which
// PowerShell cannot express as an env var ($env:X = "" deletes it), so wire
// both variables here where empty values survive.
const updaterKeyCandidates = [
  join(homedir(), ".tauri", "max-game-studio.key"),
  // Legacy filename retained so existing maintainer machines keep signing.
  join(homedir(), ".tauri", "cs2-insight-agent.key"),
];
const defaultUpdaterKey = updaterKeyCandidates.find((candidate) => existsSync(candidate));
if (!buildEnv.TAURI_SIGNING_PRIVATE_KEY && defaultUpdaterKey) {
  buildEnv.TAURI_SIGNING_PRIVATE_KEY = defaultUpdaterKey;
}
if (buildEnv.TAURI_SIGNING_PRIVATE_KEY_PASSWORD === undefined) {
  buildEnv.TAURI_SIGNING_PRIVATE_KEY_PASSWORD = "";
}

function run(command, args, env = process.env, shell = process.platform === "win32") {
  const result = spawnSync(command, args, {
    cwd: frontendRoot,
    env,
    stdio: "inherit",
    shell,
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function assertBundledFrontendVersion(root, expectedVersion) {
  const assetsRoot = join(root, "dist", "assets");
  const marker = `maxgamestudio:${expectedVersion}`;
  const sidebarBundle = readdirSync(assetsRoot, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".js"))
    .map((entry) => join(assetsRoot, entry.name))
    .find((file) => readFileSync(file, "utf8").includes(marker));
  if (!sidebarBundle) {
    throw new Error(
      `Built frontend is missing the SidebarNav version marker ${marker}`,
    );
  }
  console.log(`[desktop] validated frontend version ${expectedVersion}: ${sidebarBundle}`);
}

if (nativeRuntime) {
  if (process.platform !== "win32") {
    throw new Error("The Main native NSIS candidate must be built on Windows");
  }
  const catalog = buildEnv.MGS_MAIN_NATIVE_CATALOG;
  if (!catalog || !statSync(catalog, { throwIfNoEntry: false })?.isFile() ||
      !/^[a-f0-9]{64}$/i.test(buildEnv.MGS_MAIN_NATIVE_CATALOG_SHA256 ?? "")) {
    throw new Error("Set MGS_MAIN_NATIVE_CATALOG and its independently verified MGS_MAIN_NATIVE_CATALOG_SHA256");
  }
  const work = mkdtempSync(join(realpathSync(tmpdir()), "mgs-native-main-"));
  process.once("exit", () => {
    if (existsSync(work) && realpathSync(work) === work) rmSync(work, { recursive: true, force: true });
  });
  buildEnv.MGS_MAIN_NATIVE_CATALOG = realpathSync(catalog);
  buildEnv.MGS_MAIN_NATIVE_WORK = work;
  buildEnv.MGS_MAIN_NATIVE_GNU = isGnuBuild(buildEnv) ? "1" : "0";
  buildEnv.MGS_MAIN_NATIVE_LOADER = join(releaseRoot, "WebView2Loader.dll");
  buildEnv.MGS_MAIN_NATIVE_UNWIND = join(releaseRoot, "libunwind.dll");
} else {
  run(
    process.execPath,
    [join(frontendRoot, "scripts", "stage-python-runtime.mjs")],
    buildEnv,
    false,
  );
  run(
    process.execPath,
    [join(frontendRoot, "scripts", "stage-tauri-resources.mjs")],
    buildEnv,
    false,
  );
}

const stagedLibunwind =
  process.platform === "win32" ? stageLibunwind({ env: buildEnv, releaseRoot }) : null;
if (stagedLibunwind) {
  console.log(`[desktop] staged GNU libunwind.dll from ${stagedLibunwind.source}`);
}

const tauri = join(frontendRoot, "node_modules", "@tauri-apps", "cli", "tauri.js");
const buildConfig = {
  version,
  plugins: { updater: { endpoints: [`https://raw.githubusercontent.com/INEEDBUG/MaxGameStudio/updater/${version.includes("-") ? "beta" : "latest"}.json`] } },
};
const hasUpdaterSigningKey = Boolean(buildEnv.TAURI_SIGNING_PRIVATE_KEY);
if (!hasUpdaterSigningKey) {
  buildConfig.bundle = { createUpdaterArtifacts: false };
  console.warn("[desktop] updater private key not found — building an unsigned local installer");
}
const certificateThumbprint = buildEnv.CS2_INSIGHT_WINDOWS_CERTIFICATE_THUMBPRINT?.replaceAll(/\s/g, "");
if (certificateThumbprint) {
  buildConfig.bundle = {
    ...buildConfig.bundle,
    windows: {
      certificateThumbprint,
      digestAlgorithm: "sha256",
      timestampUrl: "http://timestamp.comodoca.com",
    },
  };
}
if (nativeRuntime) {
  // The Windows native template includes only its explicit native assets.
  buildConfig.bundle = { ...buildConfig.bundle, resources: { "bundle-resources/": null } };
}
const shortResources = nativeRuntime ? null : prepareWindowsResourceBundle(join(tauriRoot, "bundle-resources"));
if (shortResources) {
  buildConfig.bundle = {
    ...buildConfig.bundle,
    // Tauri merges config maps using JSON Merge Patch; remove the deep key.
    resources: { "bundle-resources/": null, [`${shortResources.root.replaceAll("\\", "/")}/`]: "" },
  };
  process.once("exit", () => shortResources.cleanup());
}

// A release-candidate build must never reuse a previous candidate's Vite
// output. The desktop metadata and backend marker are validated elsewhere;
// this clean build plus the post-build assertion covers the user-visible UI.
rmSync(join(frontendRoot, "dist"), { recursive: true, force: true });
run(
  process.execPath,
  [tauri, "build", "--config", JSON.stringify(buildConfig), ...(nativeRuntime ? ["--features", "native-runtime"] : [])],
  buildEnv,
  false,
);
assertBundledFrontendVersion(frontendRoot, version);

if (process.platform === "win32") {
  const loader = join(releaseRoot, "WebView2Loader.dll");
  const libunwind = join(releaseRoot, "libunwind.dll");
  const hook = join(tauriRoot, "windows", "upgrade-hooks.nsh");
  const generatedInstaller = join(releaseRoot, "nsis", "x64", "installer.nsi");
  const legacyGeneratedInstaller = join(releaseRoot, "bundle", "nsis", "x64", "installer.nsi");
  const artifact = join(
    releaseRoot,
    "bundle",
    "nsis",
    `MaxGameStudio_${version}_x64-setup.exe`,
  );
  const updaterSignature = `${artifact}.sig`;
  if (!hasUpdaterSigningKey && existsSync(updaterSignature)) {
    rmSync(updaterSignature);
  }
  const gnuBuild = isGnuBuild(buildEnv);

  if (gnuBuild && !existsSync(loader)) {
    throw new Error(`GNU Tauri build is missing required runtime loader: ${loader}`);
  }
  if (gnuBuild && !existsSync(libunwind)) {
    throw new Error(`GNU Tauri build is missing required runtime library: ${libunwind}`);
  }
  if (gnuBuild) assertPeX64(libunwind);
  if (!gnuBuild && existsSync(libunwind)) {
    throw new Error(`Non-GNU Tauri build unexpectedly contains ${libunwind}`);
  }
  const hookBody = readFileSync(hook, "utf8");
  const nativePayload = nativeRuntime ? readFileSync(join(tauriRoot, "windows", "main-native-payload.nsh"), "utf8") : "";
  if (gnuBuild && !(nativeRuntime ? nativePayload.includes('File "$%MGS_MAIN_NATIVE_LOADER%"') :
    hookBody.includes('File /a "/oname=WebView2Loader.dll"'))) {
    throw new Error("NSIS hook does not install WebView2Loader.dll beside the Tauri executable");
  }
  if (gnuBuild && !(nativeRuntime ? nativePayload.includes('File "$%MGS_MAIN_NATIVE_UNWIND%"') :
    hookBody.includes('File /a "/oname=libunwind.dll"'))) {
    throw new Error("NSIS hook does not install libunwind.dll beside the Tauri executable");
  }
  const installerScript = existsSync(generatedInstaller)
    ? generatedInstaller
    : legacyGeneratedInstaller;
  if (!existsSync(installerScript)) {
    throw new Error(`Generated NSIS script was not found beneath: ${releaseRoot}`);
  }
  const installerBody = readFileSync(installerScript, "utf8");
  if (!installerBody.includes("windows\\upgrade-hooks.nsh")) {
    throw new Error("Generated NSIS script does not include the project installer hook");
  }
  if (!installerBody.includes('!define PRODUCTNAME "MaxGameStudio"')) {
    throw new Error("Generated NSIS installer does not use the MaxGameStudio product name");
  }
  if (!installerBody.includes('CreateShortcut "$DESKTOP\\${PRODUCTNAME}.lnk"')) {
    throw new Error("Generated NSIS installer does not create the branded desktop shortcut");
  }
  if (!existsSync(artifact)) {
    throw new Error(`Tauri NSIS artifact was not created: ${artifact}`);
  }
  console.log(`[desktop] validated Windows runtime bundle: ${artifact}`);
}
