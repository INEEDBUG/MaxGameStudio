import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, rmSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveCargoReleaseRoot } from "./cargo-release-root.mjs";

const version = process.argv.slice(2).find((arg) => arg !== "--")?.trim();
if (!version || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error("Usage: pnpm run desktop:build:ver -- <x.y.z>");
  process.exit(1);
}

const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const pathKey = Object.keys(process.env).find((key) => key.toLowerCase() === "path") || "PATH";
const buildEnv = {
  ...process.env,
  CS2_INSIGHT_APP_VERSION: version,
  [pathKey]: [dirname(process.execPath), process.env[pathKey] || ""]
    .filter(Boolean)
    .join(delimiter),
};
const gnullvmBuild = /gnullvm/i.test(
  [buildEnv.RUSTUP_TOOLCHAIN, buildEnv.CARGO_BUILD_TARGET, buildEnv.HOST]
    .filter(Boolean)
    .join(" "),
);
if (gnullvmBuild && !buildEnv.CS2_LIBUNWIND_DLL) {
  const runtime = (buildEnv[pathKey] || "")
    .split(delimiter)
    .filter(Boolean)
    .map((entry) => join(entry, "libunwind.dll"))
    .find((entry) => existsSync(entry));
  if (!runtime) {
    throw new Error("gnullvm build requires libunwind.dll on PATH or CS2_LIBUNWIND_DLL");
  }
  buildEnv.CS2_LIBUNWIND_DLL = runtime;
}

// Updater (.sig) signing: fall back to the maintainer keypair generated by
// `tauri signer generate`. The default key uses an empty password, which
// PowerShell cannot express as an env var ($env:X = "" deletes it), so wire
// both variables here where empty values survive.
const updaterKeyCandidates = [
  join(homedir(), ".tauri", "max-game-studio.key"),
  // Legacy filename retained so existing maintainer machines keep signing.
  join(homedir(), ".tauri", "cs2-insight-agent.key"),
];
const defaultUpdaterKey = updaterKeyCandidates.find((candidate) => existsSync(candidate));
if (!buildEnv.TAURI_SIGNING_PRIVATE_KEY && defaultUpdaterKey) {
  buildEnv.TAURI_SIGNING_PRIVATE_KEY = defaultUpdaterKey;
}
if (buildEnv.TAURI_SIGNING_PRIVATE_KEY_PASSWORD === undefined) {
  buildEnv.TAURI_SIGNING_PRIVATE_KEY_PASSWORD = "";
}

function run(command, args, env = process.env, shell = process.platform === "win32") {
  const result = spawnSync(command, args, {
    cwd: frontendRoot,
    env,
    stdio: "inherit",
    shell,
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

run(
  process.execPath,
  [join(frontendRoot, "scripts", "stage-python-runtime.mjs")],
  buildEnv,
  false,
);
run(
  process.execPath,
  [join(frontendRoot, "scripts", "stage-tauri-resources.mjs")],
  buildEnv,
  false,
);

const tauri = join(frontendRoot, "node_modules", "@tauri-apps", "cli", "tauri.js");
const buildConfig = { version };
const hasUpdaterSigningKey = Boolean(buildEnv.TAURI_SIGNING_PRIVATE_KEY);
if (!hasUpdaterSigningKey) {
  buildConfig.bundle = { createUpdaterArtifacts: false };
  console.warn("[desktop] updater private key not found — building an unsigned local installer");
}
const certificateThumbprint = buildEnv.CS2_INSIGHT_WINDOWS_CERTIFICATE_THUMBPRINT?.replaceAll(/\s/g, "");
if (certificateThumbprint) {
  buildConfig.bundle = {
    ...buildConfig.bundle,
    windows: {
      certificateThumbprint,
      digestAlgorithm: "sha256",
      timestampUrl: "http://timestamp.comodoca.com",
    },
  };
}
run(
  process.execPath,
  [tauri, "build", "--config", JSON.stringify(buildConfig)],
  buildEnv,
  false,
);

if (process.platform === "win32") {
  const tauriRoot = join(frontendRoot, "src-tauri");
  const releaseRoot = resolveCargoReleaseRoot({
    frontendRoot,
    cargoTargetDir: buildEnv.CARGO_TARGET_DIR,
    cargoBuildTarget: buildEnv.CARGO_BUILD_TARGET,
  });
  const loader = join(releaseRoot, "WebView2Loader.dll");
  const unwindRuntime = join(releaseRoot, "libunwind.dll");
  const hook = join(tauriRoot, "windows", "upgrade-hooks.nsh");
  const generatedInstaller = join(releaseRoot, "nsis", "x64", "installer.nsi");
  const legacyGeneratedInstaller = join(releaseRoot, "bundle", "nsis", "x64", "installer.nsi");
  const artifact = join(
    releaseRoot,
    "bundle",
    "nsis",
    `MaxGameStudio_${version}_x64-setup.exe`,
  );
  const updaterSignature = `${artifact}.sig`;
  if (!hasUpdaterSigningKey && existsSync(updaterSignature)) {
    rmSync(updaterSignature);
  }
  const gnuBuild = /gnu/i.test(
    [
      buildEnv.RUSTUP_TOOLCHAIN,
      buildEnv.CARGO_BUILD_TARGET,
      buildEnv.HOST,
    ].filter(Boolean).join(" "),
  ) || existsSync(loader);

  if (gnuBuild && !existsSync(loader)) {
    throw new Error(`GNU Tauri build is missing required runtime loader: ${loader}`);
  }
  if (gnullvmBuild && !existsSync(unwindRuntime)) {
    throw new Error(`gnullvm Tauri build is missing required runtime: ${unwindRuntime}`);
  }
  const hookBody = readFileSync(hook, "utf8");
  if (gnuBuild && !hookBody.includes('File /a "/oname=WebView2Loader.dll"')) {
    throw new Error("NSIS hook does not install WebView2Loader.dll beside the Tauri executable");
  }
  if (gnullvmBuild && !hookBody.includes('File /a "/oname=libunwind.dll"')) {
    throw new Error("NSIS hook does not install libunwind.dll beside the Tauri executable");
  }
  const installerScript = existsSync(generatedInstaller)
    ? generatedInstaller
    : legacyGeneratedInstaller;
  if (!existsSync(installerScript)) {
    throw new Error(`Generated NSIS script was not found beneath: ${releaseRoot}`);
  }
  const installerBody = readFileSync(installerScript, "utf8");
  if (!installerBody.includes("windows\\upgrade-hooks.nsh")) {
    throw new Error("Generated NSIS script does not include the project installer hook");
  }
  if (!installerBody.includes('!define PRODUCTNAME "MaxGameStudio"')) {
    throw new Error("Generated NSIS installer does not use the MaxGameStudio product name");
  }
  if (!installerBody.includes('CreateShortcut "$DESKTOP\\${PRODUCTNAME}.lnk"')) {
    throw new Error("Generated NSIS installer does not create the branded desktop shortcut");
  }
  if (!existsSync(artifact)) {
    throw new Error(`Tauri NSIS artifact was not created: ${artifact}`);
  }
  console.log(`[desktop] validated Windows runtime bundle: ${artifact}`);
}
