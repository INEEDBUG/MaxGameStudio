// Unicode 15.0 default case folding (the same mapping used by Python 3.12).
// Ranges encode consecutive one-to-one folds; exceptions include full expansions.

pub(crate) fn case_fold(value: &str) -> String {
    if value.is_ascii() {
        return value.to_ascii_lowercase();
    }
    let mut folded = String::with_capacity(value.len());
    for character in value.chars() {
        let code = u32::from(character);
        let index = FOLD_RANGES.partition_point(|&(_, last, _, _)| last < code);
        if let Some(&(first, _, stride, offset)) = FOLD_RANGES.get(index) {
            if code >= first && (code - first).checked_rem(stride) == Some(0) {
                let mapped = code.checked_add_signed(offset).and_then(char::from_u32);
                folded.push(mapped.expect("valid Unicode case fold range"));
                continue;
            }
        }
        match FOLD_EXCEPTIONS.binary_search_by_key(&code, |&(source, _)| source) {
            Ok(index) => folded.push_str(FOLD_EXCEPTIONS[index].1),
            Err(_) => folded.push(character),
        }
    }
    folded
}

